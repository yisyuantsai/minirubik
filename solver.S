    la      t0, render_facelet_index

    lbu     t1, 0(t0)



    li      t2, 24

    bgeu    t1, t2, render_cube_done



    # facelet_table + index * 4

    slli    t2, t1, 2



    la      t3, render_facelet_table

    add     t3, t3, t2



