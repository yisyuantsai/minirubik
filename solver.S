# ===========================================================================

# render_init_state

#

# Convert the 14-character inline cube input into:

#

#   render_p[0..7]

#   render_o[0..7]

#

# Position/cubie 0 is the fixed FUL corner.

# ===========================================================================



render_init_state:

    la      t0, input_state



    # Fixed corner.

    la      t1, render_p

    sb      zero, 0(t1)



    la      t2, render_o

    sb      zero, 0(t2)



    # -----------------------------------------------------------------------

    # Permutation digits.

    #

    # Input cubie numbers are '1'..'7'.

    # Renderer keeps them directly as IDs 1..7.

    # -----------------------------------------------------------------------



    addi    t1, t1, 1

    li      t3, 7





render_init_p_loop:

    beqz    t3, render_init_o_begin



    lbu     t4, 0(t0)

    addi    t4, t4, -48



    sb      t4, 0(t1)



    addi    t0, t0, 1

    addi    t1, t1, 1

    addi    t3, t3, -1



    j       render_init_p_loop





render_init_o_begin:

    # '1' -> 0

    # '2' -> 1

    # '3' -> 2



    addi    t2, t2, 1

    li      t3, 7





render_init_o_loop:

    beqz    t3, render_init_done



    lbu     t4, 0(t0)

    addi    t4, t4, -49



    sb      t4, 0(t2)



    addi    t0, t0, 1

    addi    t2, t2, 1

    addi    t3, t3, -1



    j       render_init_o_loop





render_init_done:

    ret





# ===========================================================================

# render_apply_move

#

# Input:

#

#   a0 =

#       0 R

#       1 R2

#       2 R'

#       3 B

#       4 B2

#       5 B'

#       6 D

#       7 D2

#       8 D'

#

# One move is implemented as 1, 2, or 3 quarter turns.

# ===========================================================================



render_apply_move:

    la      t0, render_move_ra

    sw      ra, 0(t0)



    # -----------------------------------------------------------------------

    # Decode move into:

    #

    # render_move_face:

    #   0 = R

    #   1 = B

    #   2 = D

    #

    # render_move_turns:

    #   1, 2, or 3

    # -----------------------------------------------------------------------



    li      t0, 3

    bltu    a0, t0, render_decode_R



    li      t0, 6

    bltu    a0, t0, render_decode_B



    # D / D2 / D'

    li      t1, 2

    addi    t2, a0, -5

    j       render_decode_store





render_decode_R:

    li      t1, 0

    addi    t2, a0, 1

    j       render_decode_store





render_decode_B:

    li      t1, 1

    addi    t2, a0, -2





render_decode_store:

    la      t0, render_move_face

    sb      t1, 0(t0)



    la      t0, render_move_turns

    sb      t2, 0(t0)





render_apply_move_loop:

    la      t0, render_move_turns

    lbu     t1, 0(t0)



    beqz    t1, render_apply_move_done



    la      t0, render_move_face

    lbu     a0, 0(t0)



    jal     ra, render_quarter_turn



    la      t0, render_move_turns

    lbu     t1, 0(t0)



    addi    t1, t1, -1

    sb      t1, 0(t0)



    j       render_apply_move_loop





render_apply_move_done:

    la      t0, render_move_ra

    lw      ra, 0(t0)

    ret





# ===========================================================================

# render_quarter_turn

#

# Input:

#

#   a0 = face

#        0 R

#        1 B

#        2 D

#

# Uses the same source/twist rules as the solver.

# ===========================================================================



render_quarter_turn:

    # Each source/twist row has 7 bytes.

    #

    # face * 7 = face * 8 - face



    slli    t0, a0, 3

    sub     t0, t0, a0



    la      t1, render_source

    add     t1, t1, t0



    la      t2, render_twist

    add     t2, t2, t0



    # Current state.

    la      t3, render_p

    la      t4, render_o



    # Temporary next state.

    la      t5, render_next_p

    la      t6, render_next_o



    # Fixed FUL corner.

    sb      zero, 0(t5)

    sb      zero, 0(t6)



    # Destination index 0..6 represents positions 1..7.

    li      a1, 0





render_qt_build_loop:

    li      a2, 7

    bgeu    a1, a2, render_qt_copy_begin



    # source physical position

    add     a2, t1, a1

    lbu     a3, 0(a2)



    # destination physical position = index + 1

    addi    a4, a1, 1



    # -----------------------------------------------------------------------

    # next_p[dest] = render_p[source]

    # -----------------------------------------------------------------------



    add     a2, t3, a3

    lbu     a5, 0(a2)



    add     a2, t5, a4

    sb      a5, 0(a2)



    # -----------------------------------------------------------------------

    # next_o[dest] =

    #     (render_o[source] + twist[dest]) mod 3

    # -----------------------------------------------------------------------



    add     a2, t4, a3

    lbu     a5, 0(a2)



    add     a2, t2, a1

    lbu     a6, 0(a2)



    add     a5, a5, a6



    li      a6, 3

    bltu    a5, a6, render_qt_ori_ready



    addi    a5, a5, -3





render_qt_ori_ready:

    add     a2, t6, a4

    sb      a5, 0(a2)



    addi    a1, a1, 1

    j       render_qt_build_loop





render_qt_copy_begin:

    li      a1, 0





render_qt_copy_loop:

    li      a2, 8

    bgeu    a1, a2, render_qt_done



    # permutation

    add     a2, t5, a1

    lbu     a3, 0(a2)



    add     a2, t3, a1

    sb      a3, 0(a2)



    # orientation

    add     a2, t6, a1

    lbu     a3, 0(a2)



    add     a2, t4, a1

    sb      a3, 0(a2)



    addi    a1, a1, 1

    j       render_qt_copy_loop





render_qt_done:

    ret





