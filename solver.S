_start:

    jal     ra, parse_and_rank



    # Invalid input?

    li      t0, -1

    beq     a0, t0, solve_invalid



    # a0 = permutation rank

    # a1 = orientation rank

    jal     ra, solve_ida



    # Search failure?

    beqz    a0, solve_failed



    # Preserve solution length.

    mv      s0, a1



.if RENDER

    # Visualize the actual solution returned by IDA*.

    #

    # a0 = solution length

    mv      a0, s0

    jal     ra, render_solution

.endif



    # Replay the returned solution from the original root state.

    mv      a0, s10

    mv      a1, s11

    mv      a2, s0



    jal     ra, validate_solution



    # Preserve final state for inspection.

    mv      a3, a0

    mv      a4, a1



    # Valid solution must end at p = 0, o = 0.

    or      t0, a0, a1

    bnez    t0, validation_failed



    # Successful result:

    #

    # a0 = 1

    # a1 = solution length

    # a2 = validation success

    # a3 = final permutation rank

    # a4 = final orientation rank

    li      a0, 1

    mv      a1, s0

    li      a2, 1



    j       validation_done





solve_invalid:

    li      a0, 0

    li      a1, -1

    li      a2, 0

    li      a3, 0

    li      a4, 0



    j       validation_done





solve_failed:

    li      a0, 0

    li      a1, 0

    li      a2, 0

    li      a3, 0

    li      a4, 0



    j       validation_done





validation_failed:

    li      a0, 0

    mv      a1, s0

    li      a2, 0





validation_done:

    # Ripes exit.

    li      a7, 10

    ecall







